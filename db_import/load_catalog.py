"""Load the exported CDC catalog YAML into meida's ``series_catalog`` table.

The catalog is what makes series *discoverable*: which ones exist, what facets
pick them out, and which tool fetches them. It is generated by
:mod:`catalog` / :mod:`catalog_timeseries` into ``data/cdc_series_*.yaml``,
which is gitignored regenerable build output that no runtime code reads -- so
until it lands in the database, nothing on the server can enumerate the ~2,500
Socrata series, only fetch one whose facets you already know.

Upsert on ``(source, series_id)``, preserving ``catalog_id`` and
``created_at``, so a re-export after regenerating the catalog replaces rows in
place. Unlike :mod:`load_timeseries` this also *prunes*: the catalog is
rewritten whole on every export, so a series that disappears from it has
genuinely gone away and must not linger as an orphan row promising data the
fetch tools cannot serve.
"""
from __future__ import annotations

import re
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any, Iterator

import sqlalchemy as sa
import yaml
from sqlalchemy.dialects.postgresql import insert as pg_insert

from environment import get_meida_db_url

TABLE_NAME = "series_catalog"


class DescriptionLossError(RuntimeError):
    """A load would overwrite stored descriptions with nothing."""


def read_catalog(directory: Path, source: str) -> Iterator[dict[str, Any]]:
    """Yield every entry across one source's per-group catalog files."""
    for path in sorted(directory.glob(f"{source}_series_*.yaml")):
        doc = yaml.safe_load(path.read_text())
        for entry in doc.get("series", []):
            yield entry


#: ``2023 Q1`` -- BIS and a few CDC datasets publish quarterly bounds this way.
_QUARTER = re.compile(r"(\d{4})\s*Q([1-4])", re.IGNORECASE)


def _as_date(value: Any) -> date | None:
    """A catalog bound as a real date, snapped to the first day of its period.

    The exports carry three shapes and ``date.fromisoformat`` accepts only the
    first two characters' worth of one of them::

        2019      -> 2019-01-01
        2015-01   -> 2015-01-01     fromisoformat rejects YYYY-MM
        2023 Q1   -> 2023-01-01     fromisoformat rejects it outright

    Handling only ``YYYY`` and full ISO nulled the coverage of 442 rows -- 424
    monthly and 18 quarterly -- with no error, so they read as having no span
    at all. Snapping to the period start matches the ``YYYYMM01`` convention
    the BIS and BLS catalogs already use for their integer mirrors.
    """
    if not value:
        return None
    text = str(value).strip()
    try:
        if len(text) == 4:
            return date(int(text), 1, 1)
        quarter = _QUARTER.fullmatch(text)
        if quarter:
            year, number = quarter.groups()
            return date(int(year), 3 * (int(number) - 1) + 1, 1)
        if len(text) == 7 and text[4] == "-":
            return date(int(text[:4]), int(text[5:]), 1)
        return date.fromisoformat(text[:10])
    except ValueError:
        return None


def _retrieval(entry: dict[str, Any]) -> dict[str, Any]:
    """How this series is fetched -- the field that lets one listing serve both routes.

    ``catalog_timeseries`` writes an explicit block for the stored (WONDER and
    NVSR) entries. Socrata entries carry none, so it is derived here from what
    a ``cdc_series_data`` call actually needs: the dataset and the facets.

    Every catalogued series now has a route. The ``tool: None`` fallback stays
    as a guard -- an entry that reaches it is a bug in the generator, not a
    known gap -- and is asserted against in the tests.
    """
    if entry.get("retrieval"):
        return dict(entry["retrieval"])
    if entry.get("dataset_id"):
        return {"tool": "cdc_series_data",
                "dataset_id": entry["dataset_id"],
                "concept": entry.get("concept"),
                "facets": entry.get("facets") or {}}
    return {"tool": None, "note": "multi-query union; no single-call route"}


def _row(entry: dict[str, Any], source: str, now: datetime) -> dict[str, Any]:
    return {
        "source": source,
        "series_id": entry["series_id"],
        "dataset_id": entry.get("dataset_id"),
        "concept": entry.get("concept"),
        "title": entry.get("title") or entry["series_id"],
        "description": entry.get("description"),
        "units": entry.get("units") or entry.get("unit"),
        "frequency": entry.get("frequency"),
        "provisional": bool(entry.get("provisional")),
        "is_active": entry.get("is_active"),
        "facets": entry.get("facets") or {},
        "retrieval": _retrieval(entry),
        "observation_start": _as_date(entry.get("observation_start")),
        "observation_end": _as_date(entry.get("observation_end")),
        "updated_at": now,
    }


def load(
    directory: Path,
    source: str,
    db_url: str | None = None,
    *,
    prune: bool = True,
    now: datetime | None = None,
    allow_description_loss: bool = False,
) -> dict[str, int]:
    """Upsert one source's catalog, returning counts written and removed.

    *source* is both the namespace written to the rows and the scope of the
    prune, so passing the wrong one deletes another source's entries wholesale.
    It also selects the files: ``<source>_series_*.yaml``.

    Refuses to overwrite a stored ``description`` with nothing. A fresh export
    writes the group files with no descriptions -- they are merged in from a
    sidecar by ``descriptions.apply_to_catalog`` -- and the upsert replaces the
    column wholesale, so loading an unmerged export silently blanked all 2,526
    CDC descriptions on 2026-09-13. Pass ``allow_description_loss=True`` only
    when clearing them is the point.
    """
    now = now or datetime.now(timezone.utc)
    rows = [_row(entry, source, now) for entry in read_catalog(directory, source)]
    if not rows:
        raise FileNotFoundError(
            f"no {source}_series_*.yaml under {directory} -- regenerate the catalog first"
        )

    engine = sa.create_engine(db_url or get_meida_db_url())
    table = sa.Table(TABLE_NAME, sa.MetaData(), autoload_with=engine)
    with engine.begin() as conn:
        if not allow_description_loss:
            described = {sid for (sid,) in conn.execute(
                sa.select(table.c.series_id).where(
                    table.c.source == source, table.c.description.isnot(None)))}
            at_risk = [r["series_id"] for r in rows
                       if not r["description"] and r["series_id"] in described]
            if at_risk:
                engine.dispose()
                raise DescriptionLossError(
                    f"loading {source!r} would erase {len(at_risk)} stored "
                    f"descriptions (e.g. {at_risk[0]}) -- the export carries none "
                    f"for them. Merge the sidecar first: "
                    f"db_import.descriptions.apply_to_catalog({str(directory)!r}, "
                    f"{source!r}). Nothing was written.")
        stmt = pg_insert(table).values(rows)
        conn.execute(stmt.on_conflict_do_update(
            constraint="uq_sc_source_series",
            # catalog_id and created_at are deliberately absent: a re-export
            # must not break references or reset provenance.
            set_={c: stmt.excluded[c] for c in (
                "dataset_id", "concept", "title", "description", "units",
                "frequency", "provisional", "is_active", "facets", "retrieval",
                "observation_start", "observation_end", "updated_at")},
        ))
        removed = 0
        if prune:
            result = conn.execute(sa.delete(table).where(
                table.c.source == source,
                table.c.series_id.notin_([r["series_id"] for r in rows]),
            ))
            removed = result.rowcount or 0
    engine.dispose()
    return {"written": len(rows), "pruned": removed}


if __name__ == "__main__":
    import sys

    print(load(Path(sys.argv[1]), sys.argv[2]))
